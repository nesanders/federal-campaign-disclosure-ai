#!/usr/bin/env python3
"""Summarize out/subvendor_rows.csv + out/federal_vendors.csv into
out/findings.md: what the subvendor layer under federal vendors is made of,
which named AI tools show up in it, and -- per focus candidate -- how much
of their spending went to firms whose state filings let us see one layer
down."""
from __future__ import annotations

import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent / "out"

# CAL-ACCESS EXPN_CODE values (Form 460 instructions).
CA_CODES = {
    "TEL": "TV/cable airtime", "RAD": "Radio airtime", "PRT": "Print ads", "WEB": "Internet/digital",
    "LIT": "Campaign literature/mail", "POS": "Postage/delivery", "PHO": "Phone banks/texting",
    "CNS": "Consultants", "PRO": "Professional services", "POL": "Polling", "SAL": "Salaries",
    "PET": "Petition circulating", "CMP": "Paraphernalia", "OFC": "Office", "MTG": "Meetings/events",
    "TRC": "Candidate travel", "TRS": "Staff travel", "FND": "Fundraising events", "VOT": "Voter registration",
    "MBR": "Member communications", "IND": "Independent expenditure", "CTB": "Contributions",
    "LEG": "Legal", "FIL": "Filing fees", "CVC": "Civic donations", "TSF": "Transfers", "RFD": "Refunds",
}
MA_BUCKETS = [
    ("TV/cable airtime", r"\bTV\b|television|cable|broadcast|airtime|ott|ctv|streaming"),
    ("Radio airtime", r"radio"),
    ("Internet/digital", r"digital|online|internet|social|facebook|meta|google|youtube|programmatic|web"),
    ("Campaign literature/mail", r"mail|print|literature|lit\b|design"),
    ("Postage/delivery", r"postage|usps|delivery"),
    ("Phone banks/texting", r"phone|call|text|sms|telephone"),
    ("Polling", r"poll|survey|research|interview|sampling|data collection"),
    ("Production", r"production|video|film|edit|studio|shoot|crew|makeup|talent"),
    ("Petition circulating", r"signature|petition|circulat"),
    ("Salaries", r"salary|payroll|canvass|staff|wages"),
]


def bucket(row: dict) -> str:
    if row["state"] == "CA":
        return CA_CODES.get(row["code"], row["code"] or "Unspecified")
    for label, pat in MA_BUCKETS:
        if re.search(pat, row["purpose"], re.IGNORECASE):
            return label
    return "Other/unspecified"


def money(x: float) -> str:
    return f"${x:,.0f}"


def main() -> None:
    rows = [r for r in csv.DictReader(open(OUT / "subvendor_rows.csv", encoding="utf-8")) if not r["pass_through"]]
    for r in rows:
        r["amount"] = float(r["amount"])
    federal = {r["vendor_key"]: r for r in csv.DictReader(open(OUT / "federal_vendors.csv", encoding="utf-8"))}
    summary = {r["vendor_key"]: r for r in csv.DictReader(open(OUT / "vendor_summary.csv", encoding="utf-8"))}

    total = sum(r["amount"] for r in rows)
    ai_rows = [r for r in rows if r["ai_vendor_ids"]]
    generic_rows = [r for r in rows if r["generic_ai_hit"] and not r["ai_vendor_ids"]]
    ai_total = sum(r["amount"] for r in ai_rows)

    lines: list[str] = []
    w = lines.append
    w("# What federal campaign vendors pay for, one layer down\n")
    w("Generated by `analysis/subvendors/report.py`. Federal vendors = every non-individual payee on FEC "
      "Schedule B, 2020-2026. State layer = Massachusetts OCPF subvendor reports and California CAL-ACCESS "
      "payments made by an agent/contractor on a committee's behalf (latest amendment only). Credit cards, "
      "payroll processors and payment platforms are excluded as pass-throughs.\n")
    w(f"- Subvendor rows under federal vendors: **{len(rows):,}**, totaling **{money(total)}**")
    w(f"- Rows naming a tool in the project's AI taxonomy (high confidence): **{len(ai_rows)}**, "
      f"**{money(ai_total)}** ({ai_total / total:.2%} of subvendor dollars)")
    w(f"- Additional rows with generic AI language (\"AI\", \"artificial intelligence\"...), reviewed by hand below: "
      f"**{len(generic_rows)}**, {money(sum(r['amount'] for r in generic_rows))}\n")

    w("## What the subvendor layer is made of\n")
    w("| Category | Subvendor $ | Share |\n|---|---:|---:|")
    by_bucket = Counter()
    for r in rows:
        by_bucket[bucket(r)] += r["amount"]
    for label, amt in by_bucket.most_common(12):
        w(f"| {label} | {money(amt)} | {amt / total:.1%} |")
    w("")

    w("## Named AI tools in the subvendor layer\n")
    w("| AI tool | Era | Subvendor $ | Rows | Paid by (federal vendors) |\n|---|---|---:|---:|---|")
    by_tool: dict[str, dict] = defaultdict(lambda: {"amount": 0.0, "rows": 0, "era": "", "via": Counter()})
    for r in ai_rows:
        for vid, era in zip(r["ai_vendor_ids"].split(";"), r["ai_vendor_eras"].split(";")):
            t = by_tool[vid]
            t["amount"] += r["amount"]
            t["rows"] += 1
            t["era"] = era
            t["via"][federal[r["vendor_key"]]["display_name"]] += r["amount"]
    for vid, t in sorted(by_tool.items(), key=lambda kv: -kv[1]["amount"]):
        via = "; ".join(f"{n} ({money(a)})" for n, a in t["via"].most_common(6))
        w(f"| {vid} | {t['era']} | {money(t['amount'])} | {t['rows']} | {via} |")
    w("")

    w("## Generic-AI-language rows (not in the taxonomy)\n")
    w("| State | Federal vendor | Subvendor | Purpose | $ |\n|---|---|---|---|---:|")
    grouped = Counter()
    for r in generic_rows:
        grouped[(r["state"], federal[r["vendor_key"]]["display_name"], r["subvendor"], r["purpose"])] += r["amount"]
    for (st, fv, sub, purpose), amt in grouped.most_common(25):
        w(f"| {st} | {fv} | {sub} | {purpose} | {money(amt)} |")
    w("")

    w("## Federal vendors whose state filings show AI subvendors\n")
    w("| Federal vendor | Federal $ (2020-26) | Federal committees | AI tool(s) one layer down | All state subvendor $ |\n"
      "|---|---:|---:|---|---:|")
    ai_by_vendor: dict[str, Counter] = defaultdict(Counter)
    for r in ai_rows + generic_rows:
        tool = r["ai_vendor_ids"] or f"{r['subvendor']} (\"{r['generic_ai_hit']}\")"
        ai_by_vendor[r["vendor_key"]][tool] += r["amount"]
    for key, tools in sorted(ai_by_vendor.items(), key=lambda kv: -float(federal[kv[0]]["federal_amount"])):
        fed = federal[key]
        tool_str = "; ".join(f"{t} {money(a)}" for t, a in tools.most_common())
        w(f"| {fed['display_name']} | {money(float(fed['federal_amount']))} | {fed['committees']} | {tool_str} | "
          f"{money(float(summary[key]['state_subvendor_amount']))} |")
    w("")

    # Focus candidates: how much of their federal spending went to firms that
    # also appear as primary vendors in state subvendor data.
    w("## Focus candidates: how much of their spending can be traced one layer down\n")
    w("Share of each candidate's federal spending (2020-26, non-individual payees) that went to firms which also "
      "file at least $10,000 of state subvendor detail. That detail describes the firm's state work, not this candidate's account.\n")
    w("| Candidate | Federal $ to firms with state subvendor data | Top such firms |\n|---|---:|---|")
    focus_pat = re.compile(r"(.+?) \(\$([\d,]+)\)")
    per_cand: dict[str, Counter] = defaultdict(Counter)
    for key, fed in federal.items():
        # $10K floor drops incidental matches (airlines, delivery apps) whose
        # state "subvendor" rows are a reimbursement or two.
        if key not in summary or summary[key]["pass_through"] or float(summary[key]["state_subvendor_amount"]) < 10000:
            continue
        for part in fed["focus_candidates"].split("; "):
            m = focus_pat.match(part)
            if m:
                per_cand[m.group(1)][fed["display_name"]] += float(m.group(2).replace(",", ""))
    for cand, firms in sorted(per_cand.items(), key=lambda kv: -sum(kv[1].values())):
        top = "; ".join(f"{n} ({money(a)})" for n, a in firms.most_common(4))
        w(f"| {cand} | {money(sum(firms.values()))} | {top} |")
    w("")

    (OUT / "findings.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
